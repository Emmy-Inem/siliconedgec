CREATE OR REPLACE FUNCTION public.automation_on_submission_grade()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.queue_automation(NEW.user_id, 'first_assignment_submitted', NULL, jsonb_build_object('assignment_id', NEW.assignment_id));
  ELSIF NEW.grade IS NOT NULL AND OLD.grade IS DISTINCT FROM NEW.grade THEN
    PERFORM public.queue_automation(NEW.user_id, 'assignment_graded', NEW.id::text, jsonb_build_object('assignment_id', NEW.assignment_id, 'grade', NEW.grade));
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_automation_on_submission_grade
AFTER INSERT OR UPDATE ON public.assignment_submissions
FOR EACH ROW EXECUTE FUNCTION public.automation_on_submission_grade();
