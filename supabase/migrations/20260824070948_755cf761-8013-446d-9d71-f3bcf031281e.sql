4. **Month 6:** Interview preparation — architecture discussions, troubleshooting scenarios, and a clear write-up of every project.

## Portfolio projects that stand out

- A migration case study: move a small app from a single VM to managed services and document the trade-offs.
- A cost review: take a deliberately wasteful architecture and show what you changed and why.
