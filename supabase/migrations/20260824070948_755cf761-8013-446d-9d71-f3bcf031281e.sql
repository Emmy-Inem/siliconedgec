Pick **one** cloud and go deep. Breadth across three providers reads as shallow on a CV.

## A realistic six-month plan

1. **Months 1–2:** Linux and networking fundamentals, plus a foundational certification such as AZ-900 or AWS Cloud Practitioner.
2. **Months 3–4:** An associate-level track (AZ-104 or Solutions Architect Associate) while building two portfolio projects.
